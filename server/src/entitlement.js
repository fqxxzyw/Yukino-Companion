import {base64url, canonicalJson, fail, fromBase64url} from './util.js';

// ECDSA P-256 (ES256) is supported by Workers WebCrypto and by Node's WebCrypto,
// and lets the desktop cache a server-confirmed entitlement snapshot without
// ever holding a signing secret. Snapshots are only a cached confirmed record:
// they are not API access tokens and cannot authorize cloud requests.
const ALG = {name: 'ECDSA', namedCurve: 'P-256'};
const SIGN = {name: 'ECDSA', hash: 'SHA-256'};

function privateJwk(env) {
  const raw = env.SNAPSHOT_PRIVATE_JWK;
  if (!raw) return null;
  let value;
  try { value = typeof raw === 'string' ? JSON.parse(raw) : raw; }
  catch { fail(503, 'server_misconfigured', '权益签名密钥格式无效。'); }
  if (value?.kty !== 'EC' || value?.crv !== 'P-256' || !value?.d) fail(503, 'server_misconfigured', '权益签名密钥格式无效。');
  return value;
}

export function publicJwkFromEnv(env) {
  if (env.SNAPSHOT_PUBLIC_JWK) {
    try { return JSON.parse(env.SNAPSHOT_PUBLIC_JWK); } catch { return null; }
  }
  const privateValue = privateJwk(env);
  if (!privateValue) return null;
  return {kty: 'EC', crv: 'P-256', x: privateValue.x, y: privateValue.y, ext: true, key_ops: ['verify']};
}

export async function signSnapshot(payload, env) {
  const jwk = privateJwk(env);
  if (!jwk) fail(503, 'snapshot_not_configured', '云端权益签名尚未配置。');
  const key = await crypto.subtle.importKey('jwk', jwk, ALG, false, ['sign']);
  const bytes = new TextEncoder().encode(canonicalJson(payload));
  const signature = await crypto.subtle.sign(SIGN, key, bytes);
  return {
    alg: 'ES256',
    keyId: env.SNAPSHOT_KEY_ID || 'dev-2026-11',
    snapshot: payload,
    signature: base64url(signature),
  };
}

export async function verifySnapshot(envelope, publicJwk) {
  if (!envelope || envelope.alg !== 'ES256' || !envelope.signature || !envelope.snapshot) return false;
  const key = await crypto.subtle.importKey('jwk', publicJwk, ALG, false, ['verify']);
  const bytes = new TextEncoder().encode(canonicalJson(envelope.snapshot));
  return crypto.subtle.verify(SIGN, key, fromBase64url(envelope.signature), bytes);
}

export function entitlementPayload({userId, affection, loginDays, skins, now, rulesVersion}) {
  return {
    v: 1,
    uid: userId,
    affection,
    loginDays,
    skinIds: [...skins].sort(),
    rulesVersion,
    issuedAt: now,
  };
}

// Used by the local dev server to generate a throwaway key pair. Production
// secrets are generated by server/scripts/generate-secrets.mjs and never
// committed.
export async function generateKeyPair() {
  const pair = await crypto.subtle.generateKey(ALG, true, ['sign', 'verify']);
  return {
    privateJwk: await crypto.subtle.exportKey('jwk', pair.privateKey),
    publicJwk: await crypto.subtle.exportKey('jwk', pair.publicKey),
  };
}
